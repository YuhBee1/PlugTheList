<p>PlugTheList uses only the cookies it needs to work. We do not use advertising or cross-site tracking cookies.</p>
<ul>
<li><strong>Session cookie</strong> (<code>ptl_sid</code>): keeps you signed in across plugthelist.com subdomains. It is HttpOnly and Secure.</li>
<li><strong>Security cookie</strong> (<code>ptl_g</code>): protects forms from forgery when you are signed out.</li>
<li><strong>Message cookie</strong> (<code>ptl_flash</code>): shows a one-time confirmation message.</li>
<li><strong>Theme setting</strong>: your light or dark choice is stored in your browser's local storage.</li>
</ul>
<p>Because these are strictly necessary, they do not need a consent banner. If we add analytics or marketing cookies later we will ask first.</p>
